const catalogs: Record<Language, TranslationCatalog> = { en: english, uk: ukrainian };

export type TranslationValues = Record<string, string | number>;
export type Translate = (key: TranslationKey, values?: TranslationValues) => string;

export function translate(
  language: Language,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  return catalogs[language][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    String(values[name] ?? match),
  );
}

export function languageLocale(language: Language): string {
  return language === 'uk' ? 'uk-UA' : 'en-US';
}
